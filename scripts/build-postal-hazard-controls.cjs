function classify(item) {
  const matched = rules.find(rule => rule.test.test(item));
  if (matched) return matched;
  return {
    hazard: '점검항목 관련 안전보건조치 미흡', accident: '상해·건강장해 또는 사고 확대',
    controls: ['해당 작업 또는 설비의 사용을 일시 중지하고 위험 원인을 제거·보수한다.', '담당자가 정상 상태와 안전조치 이행을 확인한 뒤 작업을 재개한다.', '점검·조치·확인 결과를 기록하고 관련 작업자에게 공유한다.'],
    keywords: [...new Set(item.replace(/[?(),·]/g, ' ').split(/\s+/).filter(word => word.length >= 2).slice(0, 7))],
    basis: [],
  };
}

function csv(value) {
  const text = Array.isArray(value) ? value.join(' | ') : String(value ?? '');
  return `"${text.replace(/"/g, '""')}"`;
}

const blocks = fs.existsSync(inputPath)
  ? splitBlocks(fs.readFileSync(inputPath, 'utf8'))
  : new Map();
const counters = new Map();
const records = [];
for (const [file, task, domain] of filePlan) {
  const items = extractItems(file, blocks.get(file) || []);
  if (!items.length) throw new Error(`${file}에서 점검항목을 추출하지 못했습니다.`);
  for (const item of items) {
    if (/^기록하고 있는가\?$/.test(item) && records.at(-1)?.task === task) {
      records.at(-1).check_item = records.at(-1).check_item.replace(/\?$/, '') + ' 기록하고 있는가?';
      continue;
    }
    const number = (counters.get(task) || 0) + 1;
    counters.set(task, number);
    const detail = classify(item);
    records.push({
      id: `postal-control-${crypto.createHash('sha1').update(`${task}|${number}|${item}`).digest('hex').slice(0, 12)}`,
      domain,
      task,
      item_no: number,
      check_item: item,
      hazard: detail.hazard,
      accident_type: detail.accident,
      controls: detail.controls,
      legal_basis: detail.basis,
      keywords: [...new Set([task, ...detail.keywords])],
      review_status: /[\\{}#]|[疋甛膺邕蹕翠靉罸辱筩]/.test(item) ? '원문 대조 필요' : '검토 대기',
    });
  }
}

