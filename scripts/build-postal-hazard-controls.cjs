function cleanText(value) {
  return String(value || '')
    .normalize('NFKC')
    .replace(/\r/g, ' ')
    .replace(/[•·]/g, '·')
    .replace(/바c/g, '바닥')
    .replace(/님이심|님이실|어짐/g, '넘어짐')
    .replace(/부작/g, '부착')
    .replace(/작용/g, '착용')
    .replace(/페기/g, '폐기')
    .replace(/아자사고/g, '아차사고')
    .replace(/쥐급|쉬급/g, '취급')
    .replace(/주락/g, '추락')
    .replace(/일페/g, '밀폐')
    .replace(/자량/g, '차량')
    .replace(/중돌/g, '충돌')
    .replace(/근곤격/g, '근골격')
    .replace(/물실안전보간케자료|물실안전보건자료/g, '물질안전보건자료')
    .replace(/파(?:É|己|C|e|근시|근것|근\^월|근겟|끗위)?겟?트/g, '파렛트')
    .replace(/지게자/g, '지게차')
    .replace(/견인자/g, '견인차')
    .replace(/전동파근?겟?트럭/g, '전동파렛트럭')
    .replace(/개페/g, '개폐')
    .replace(/누전자단기/g, '누전차단기')
    .replace(/접지지항/g, '접지저항')
    .replace(/자단/g, '차단')
    .replace(/호홉기/g, '호흡기')
    .replace(/제계/g, '체계')
    .replace(/대서요령/g, '대처요령')
    .replace(/실비/g, '설비')
    .replace(/정소/g, '청소')
    .replace(/부딛/g, '부딪')
    .replace(/넘넘(?:넘)?어짐/g, '넘어짐')
    .replace(/운저자|운서자/g, '운전자')
    .replace(/지계자/g, '지게차')
    .replace(/한들 노브/g, '핸들 노브')
    .replace(/승치석/g, '운전석')
    .replace(/중전시설/g, '충전시설')
    .replace(/화x/g, '화재')
    .replace(/대저/g, '대처')
    .replace(/화보/g, '확보')
    .replace(/70m\b/g, '70cm')
    .replace(/위험아|위험시/g, '위험이')
    .replace(/부작부/g, '부착부')
    .replace(/1\.596/g, '1.5%')
    .replace(/많은가/g, '않은가')
    .replace(/되괴/g, '되고')
    .replace(/살 작동/g, '잘 작동')
    .replace(/기타\s*\([^)]*\).*/g, '')
    .replace(/[「」]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}

function splitBlocks(text) {
  const map = new Map();
  for (const chunk of text.split(/^===== /m).slice(1)) {
    const [header, ...lines] = chunk.split('\n');
    map.set(header.replace(/ =====\s*$/, '').trim(), lines);
  }
  return map;
}

function extractItems(file, lines) {
  if (manualItems[file]) return manualItems[file];
  const ignored = /^(?:구분|구문|비고|대상|비대상|위험성.*|유해.*점검사항|기타.*|[0-9]+|[가-힣]?)$/;
  let text = lines.map(line => line.trim()).filter(line => line && !ignored.test(line)).join(' ');
  text = cleanText(text);
  const start = firstPhrase[file];
  const at = text.indexOf(start);
  if (at >= 0) text = text.slice(at);
  text = text.replace(/(있는가|없는가|않는가|하는가|되는가|적합한가|받았는가|유지하는가|실시하는가|용이한가)(?!\?)/g, '$1?');
  const items = text.split('?').map(item => cleanText(item).replace(/^\d+\s*/, '')).filter(item => item.length >= 12);
  return [...(injected[file] || []), ...items.map(item => `${item}?`)];
}

