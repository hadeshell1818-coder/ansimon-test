const assert = require('node:assert/strict');
const XLSX = require('xlsx-js-style');
const { WIDTHS, exportRows, configureExport } = require('../risk-export-layout.cjs');
const factor = '높은 곳에서 소포를 운반하는 작업 중 낙하와 추락 위험. '.repeat(100);
const reduction = '작업 담당자가 통로를 확보하고 적재 높이를 확인합니다.\n'.repeat(80);
const { rows, heights } = exportRows([{factor,reduction,riskLevel:'상',owner:'담당자',referenceText:'https://www.kosha.or.kr/guide'}]);
assert.ok(rows.length>1);
assert.equal(rows.map(r=>r[1]).join('').replace(/\n/g,''),factor);
assert.equal(rows.map(r=>r[3]).join('\n').replace(/\n/g,''),reduction.replace(/\n/g,''));
assert.ok(heights.every(h=>h<=280));
assert.ok(WIDTHS.reduce((a,b)=>a+b,0)<150);
const book=XLSX.utils.book_new();
const sheet=XLSX.utils.aoa_to_sheet([['공정'],[],['번호','요인','수준','대책','예정','완료','담당','결과','근거'],...rows]);
sheet['!cols']=WIDTHS.map(wch=>({wch}));sheet['!rows']=[{hpt:30},{hpt:8},{hpt:42},...heights.map(hpt=>({hpt}))];
XLSX.utils.book_append_sheet(book,sheet,'소포');
const buffer=configureExport(XLSX.write(book,{type:'buffer',bookType:'xlsx'}));
const zip=XLSX.CFB.read(buffer,{type:'buffer'});
const index=zip.FullPaths.findIndex(p=>p.endsWith('xl/worksheets/sheet1.xml'));
const xml=zip.FileIndex[index].content.toString('utf8');
assert.match(xml,/zoomScale="100"/);assert.match(xml,/fitToWidth="1"/);assert.match(xml,/fitToHeight="0"/);assert.match(xml,/orientation="landscape"/);assert.match(xml,/state="frozen"/);
assert.ok(xml.indexOf('<sheetViews>')<xml.indexOf('<cols>'),'OOXML sheet views precede column definitions');
const read=XLSX.read(buffer,{type:'buffer'});assert.ok(read.Sheets['소포']);
assert.equal(XLSX.utils.sheet_to_json(read.Sheets['소포'],{header:1})[3][1],rows[0][1]);
console.log('PASS: long Korean content preserved across continuation rows, fitted row heights, compact columns, 100% zoom, A4 landscape and XLSX roundtrip');
